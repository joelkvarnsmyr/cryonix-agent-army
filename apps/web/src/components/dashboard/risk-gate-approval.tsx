'use client';
import { useTankState } from '@/hooks/useTankState';
import { Card, CardContent, CardHeader, CardTitle, useToast } from '@cryonix/ui';
import { Bot, CheckCircle } from 'lucide-react';

export function RiskGateApproval() {
    const { pendingTrades } = useTankState();

    if (!pendingTrades.data || pendingTrades.data.length === 0) {
        return (
            <Card className="border-dashed">
                <CardContent className="pt-6 flex flex-col items-center text-muted-foreground">
                    <CheckCircle className="h-8 w-8 mb-2 opacity-50" />
                    <p className="text-sm">Autonomous pipeline clear. No signals pending.</p>
                </CardContent>
            </Card>
        );
    }

    return (
        <Card>
            <CardHeader>
                <CardTitle className="flex items-center gap-2 text-primary/80">
                    <Bot className="h-5 w-5" />
                    Autonomous Pipeline: Pending Signals
                </CardTitle>
            </CardHeader>
            <CardContent className="space-y-3">
                <p className="text-xs text-muted-foreground">
                    The following signals have been generated by the engine and are awaiting processing by the autonomous auto-trader. No manual action is required.
                </p>
                {pendingTrades.data.map((signal: any, idx: number) => (
                    <div key={idx} className="flex items-center justify-between p-3 bg-background border rounded-lg">
                        <div>
                            <div className="font-bold">{signal.action} {signal.symbol}</div>
                            <div className="text-xs text-muted-foreground">
                                Confidence: {(signal.confidence * 100).toFixed(1)}% | Patterns: {signal.patterns?.join(', ') || 'N/A'}
                            </div>
                        </div>
                        <div className="text-xs font-mono bg-muted text-muted-foreground px-2 py-1 rounded">
                            AWAITING AI VALIDATION
                        </div>
                    </div>
                ))}
            </CardContent>
        </Card>
    );
}
